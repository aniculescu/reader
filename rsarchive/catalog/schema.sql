-- rsarchive.catalog — canonical SQLite schema (source of truth for the catalog).
--
-- Design notes (see catalog/DESIGN.md for the full contract):
--   * This file is the ONLY place the DDL lives. `catalog.db` is generated from it;
--     `dump.sql` (a `.iterdump()` text dump) is the committed, diffable snapshot of
--     BOTH schema and data. schema.sql + dump.sql together version the store.
--   * Everything is `IF NOT EXISTS` so `catalog init` is idempotent and re-runnable.
--   * The physical table `refs` IS the logical "references" entity from the brief;
--     it is renamed only because `references` is a SQL reserved word (REFERENCES is a
--     column-constraint keyword) and quoting it everywhere is error-prone.
--   * The `lectures` table round-trips to/from rsarchive.models.Lecture. Scalar
--     bibliographic fields get their own columns; the three rich, nested structures
--     that have no flat representation (positions / body / footnotes) are stored as
--     JSON text columns so export can reproduce Lecture.to_json() losslessly. Images
--     round-trip via the `tafeln` table + `images_json` (sketches); cross_refs are
--     regenerated by rsarchive.metadata and are NOT stored here.
--   * Target: SQLite via stdlib sqlite3, Python 3.12. FTS5 is optional (guarded).
--   * Columns added to a table AFTER it first shipped are declared here in their
--     CREATE TABLE (so fresh DBs get them) AND listed, in the same order, in
--     db._ADDED_COLUMNS (so an existing DB gets them via ALTER TABLE ADD COLUMN before
--     this file is re-applied). Their declarations must therefore be ALTER-safe: no
--     UNIQUE/PRIMARY KEY, a constant DEFAULT when NOT NULL, and REFERENCES columns
--     defaulting to NULL. Indexes on such columns live in this file; db.migrate adds
--     the columns first so those CREATE INDEX statements never see a missing column.

PRAGMA foreign_keys = ON;

-- --------------------------------------------------------------------------- meta

CREATE TABLE IF NOT EXISTS schema_meta (
    key   TEXT PRIMARY KEY,
    value TEXT
);
-- db.init_db / db.migrate record ('schema_version', db.SCHEMA_VERSION); bump on any
-- DDL change (see the version history in db.py).

-- ------------------------------------------------------------------------ volumes

-- One GA volume (Gesamtausgabe). Populated from RSCatalog.docx (volume-level metadata).
CREATE TABLE IF NOT EXISTS volumes (
    ga                TEXT PRIMARY KEY,          -- bare token, e.g. "228", "89", "089a"
    title_en          TEXT NOT NULL DEFAULT '',  -- English volume title (alpha tables)
    title_de          TEXT NOT NULL DEFAULT '',  -- German title ("German:" detail line)
    titles_in_volume  TEXT NOT NULL DEFAULT '',  -- "Titles in this Volume: ..." verbatim
    lecture_count     INTEGER,                   -- count cell from the alpha tables
    date_range        TEXT NOT NULL DEFAULT '',  -- "Dates:" line, e.g. "19 Oct 1901 – 26 Apr 1902"
    locations         TEXT NOT NULL DEFAULT '',  -- "Location:" line, e.g. "Dornach, Mannheim"
    created_at        TEXT NOT NULL DEFAULT (datetime('now')),
    updated_at        TEXT NOT NULL DEFAULT (datetime('now')),
    -- v3: 1 = in scope for the published catalog (bodies ingested / to be ingested).
    -- Set by ingest.ingest_ga and ingest.set_curated; never inferred from titles.
    curated           INTEGER NOT NULL DEFAULT 0
);

CREATE INDEX IF NOT EXISTS ix_volumes_curated ON volumes(curated);

-- ----------------------------------------------------------------------- lectures

-- One lecture / article. `url` is the authoritative merge key (matches models.Lecture).
CREATE TABLE IF NOT EXISTS lectures (
    id             INTEGER PRIMARY KEY,
    ga             TEXT NOT NULL REFERENCES volumes(ga) ON UPDATE CASCADE,
    url            TEXT NOT NULL UNIQUE,          -- authoritative GA-index href (merge key)
    seq_in_volume  INTEGER,                       -- 1-based order within its volume/index
    title_en       TEXT NOT NULL DEFAULT '',
    title_de       TEXT NOT NULL DEFAULT '',
    date_iso       TEXT NOT NULL DEFAULT '',      -- "YYYY-MM-DD" ("" if unknown -> sorts last)
    date_display   TEXT NOT NULL DEFAULT '',      -- "September 8, 1923"
    city           TEXT NOT NULL DEFAULT '',
    edition_path   TEXT NOT NULL DEFAULT '',      -- e.g. "English/SOL2024", "Singles"
    translator     TEXT NOT NULL DEFAULT '',
    cycle_title    TEXT NOT NULL DEFAULT '',
    cycle_url      TEXT NOT NULL DEFAULT '',
    book_title     TEXT NOT NULL DEFAULT '',
    summary        TEXT NOT NULL DEFAULT '',      -- LLM/manual abstract (later pass)
    -- Rich model structures with no flat form; JSON text (see mapping.py):
    positions_json TEXT NOT NULL DEFAULT '{}',    -- models.Positions.to_json()
    body_json      TEXT NOT NULL DEFAULT '[]',    -- [Block.to_json(), ...]
    footnotes_json TEXT NOT NULL DEFAULT '[]',    -- [Footnote.to_json(), ...]
    images_json    TEXT NOT NULL DEFAULT '{}',    -- models.Images.to_json() (sketches; tafeln also mirrored in `tafeln`)
    created_at     TEXT NOT NULL DEFAULT (datetime('now')),
    updated_at     TEXT NOT NULL DEFAULT (datetime('now'))
);

CREATE INDEX IF NOT EXISTS ix_lectures_ga        ON lectures(ga);
CREATE INDEX IF NOT EXISTS ix_lectures_date      ON lectures(date_iso);
CREATE INDEX IF NOT EXISTS ix_lectures_city      ON lectures(city);
CREATE INDEX IF NOT EXISTS ix_lectures_ga_seq    ON lectures(ga, seq_in_volume);
-- Chronological reads (the canonical export order); NULL/'' dates last is handled in SQL.
CREATE INDEX IF NOT EXISTS ix_lectures_date_url  ON lectures(date_iso, url);

-- ----------------------------------------------------------------------- subjects

-- Hierarchical subject taxonomy (parent_id -> subjects.id). Seeded from subjects_seed.py.
CREATE TABLE IF NOT EXISTS subjects (
    id          INTEGER PRIMARY KEY,
    name        TEXT NOT NULL,
    slug        TEXT UNIQUE,                       -- stable id for seeding / CLI tagging
    parent_id   INTEGER REFERENCES subjects(id) ON DELETE CASCADE,
    description TEXT NOT NULL DEFAULT '',
    seq         INTEGER,                           -- order among siblings (PRESERVE stated order)
    UNIQUE(parent_id, name)
);

CREATE INDEX IF NOT EXISTS ix_subjects_parent ON subjects(parent_id, seq);

-- v3: controlled vocabulary of the POINT OF VIEW from which a lecture approaches a
-- subject (cosmological, Christological, ...). Seeded from subjects_seed.PERSPECTIVES
-- (upsert by slug); the user may add rows. `seq` = display order.
CREATE TABLE IF NOT EXISTS perspectives (
    id          INTEGER PRIMARY KEY,
    slug        TEXT NOT NULL UNIQUE,
    name        TEXT NOT NULL,
    description TEXT NOT NULL DEFAULT '',
    seq         INTEGER
);

-- Junction: which subjects a lecture is tagged with. The PK keeps one row (hence one
-- perspective) per (lecture, subject). LLM tags arrive as status='proposed' and only
-- 'approved' rows are published; subjects.tag_lecture never lets an LLM re-run
-- overwrite a human review decision.
CREATE TABLE IF NOT EXISTS lecture_subjects (
    lecture_id INTEGER NOT NULL REFERENCES lectures(id) ON DELETE CASCADE,
    subject_id INTEGER NOT NULL REFERENCES subjects(id) ON DELETE CASCADE,
    seq        INTEGER,                            -- study order within the subject (NULL = unordered)
    source     TEXT NOT NULL DEFAULT 'manual'
                 CHECK (source IN ('manual','llm','catalog')),
    confidence REAL,                               -- 0..1 for llm-sourced tags; NULL otherwise
    -- v3 (appended in this order by db._ADDED_COLUMNS on older DBs):
    perspective_id INTEGER REFERENCES perspectives(id) ON DELETE SET NULL,
    approach_note  TEXT NOT NULL DEFAULT '',       -- free text: how this lecture comes at the theme
    status         TEXT NOT NULL DEFAULT 'approved'
                     CHECK (status IN ('proposed','approved','rejected')),
    evidence       TEXT NOT NULL DEFAULT '',       -- supporting quote (LLM proposals)
    PRIMARY KEY (lecture_id, subject_id)
);

CREATE INDEX IF NOT EXISTS ix_ls_subject     ON lecture_subjects(subject_id, seq);
CREATE INDEX IF NOT EXISTS ix_ls_lecture     ON lecture_subjects(lecture_id);
CREATE INDEX IF NOT EXISTS ix_ls_status      ON lecture_subjects(status);
CREATE INDEX IF NOT EXISTS ix_ls_perspective ON lecture_subjects(perspective_id);

-- --------------------------------------------------------------- references (refs)

-- The reference graph. from_lecture_id is always known; the target is NULL until a
-- cue is resolved. source='rule' for the rule-based extractor; 'llm'/'manual' later.
-- v3: a ref may point at a lecture (to_lecture_id), a published cycle (to_cycle_id) or
-- a GA volume / book (to_ga); `target_type` says which one is meant ('unknown' while
-- unresolved). `origin` separates Steiner's own words (body) from editors' footnotes;
-- `relation` separates "yesterday"-style continuations inside a cycle from genuine
-- recalls and citations of other works; `status` gates publication like tags.
CREATE TABLE IF NOT EXISTS refs (
    id              INTEGER PRIMARY KEY,
    from_lecture_id INTEGER NOT NULL REFERENCES lectures(id) ON DELETE CASCADE,
    to_lecture_id   INTEGER REFERENCES lectures(id) ON DELETE SET NULL,
    kind            TEXT NOT NULL CHECK (kind IN ('explicit','implicit')),
    cue_text        TEXT NOT NULL DEFAULT '',      -- the matched snippet
    target_hint     TEXT NOT NULL DEFAULT '',      -- raw target phrase (date/GA/"previous lecture")
    resolved        INTEGER NOT NULL DEFAULT 0,    -- 0/1 boolean
    source          TEXT NOT NULL DEFAULT 'rule'
                      CHECK (source IN ('rule','llm','manual')),
    confidence      REAL,
    -- v3 (appended in this order by db._ADDED_COLUMNS on older DBs):
    target_type     TEXT NOT NULL DEFAULT 'unknown'
                      CHECK (target_type IN ('lecture','cycle','volume','unknown')),
    to_cycle_id     INTEGER REFERENCES cycles(id) ON DELETE SET NULL,
    to_ga           TEXT REFERENCES volumes(ga) ON UPDATE CASCADE,
    origin          TEXT NOT NULL DEFAULT 'body'
                      CHECK (origin IN ('body','footnote')),
    relation        TEXT NOT NULL DEFAULT 'recall'
                      CHECK (relation IN ('continuation','recall','citation')),
    status          TEXT NOT NULL DEFAULT 'approved'
                      CHECK (status IN ('proposed','approved','rejected'))
);

CREATE INDEX IF NOT EXISTS ix_refs_from     ON refs(from_lecture_id);
CREATE INDEX IF NOT EXISTS ix_refs_to       ON refs(to_lecture_id);
CREATE INDEX IF NOT EXISTS ix_refs_resolved ON refs(resolved);
CREATE INDEX IF NOT EXISTS ix_refs_to_cycle ON refs(to_cycle_id);
CREATE INDEX IF NOT EXISTS ix_refs_to_ga    ON refs(to_ga);
CREATE INDEX IF NOT EXISTS ix_refs_status   ON refs(status);
-- Idempotency for the rule extractor: don't insert the same cue twice per lecture.
CREATE UNIQUE INDEX IF NOT EXISTS ux_refs_dedupe
    ON refs(from_lecture_id, kind, cue_text, target_hint);

-- v3: a ref whose target row disappears (ON DELETE SET NULL on to_lecture_id /
-- to_cycle_id) must not stay "approved + resolved" with no target — it would silently
-- drop out of both the review queue and the export. Send it back to review instead.
CREATE TRIGGER IF NOT EXISTS refs_target_lost
AFTER UPDATE OF to_lecture_id, to_cycle_id, to_ga ON refs
WHEN (new.target_type = 'lecture' AND new.to_lecture_id IS NULL)
  OR (new.target_type = 'cycle' AND new.to_cycle_id IS NULL)
  OR (new.target_type = 'volume' AND new.to_ga IS NULL)
BEGIN
    UPDATE refs SET target_type = 'unknown', resolved = 0, status = 'proposed'
    WHERE id = new.id;
END;

-- ---------------------------------------------------------------------- sequences

-- Named, ordered study orders (e.g. "Gospel study order").
CREATE TABLE IF NOT EXISTS sequences (
    id          INTEGER PRIMARY KEY,
    name        TEXT NOT NULL UNIQUE,
    description TEXT NOT NULL DEFAULT ''
);

CREATE TABLE IF NOT EXISTS sequence_items (
    sequence_id INTEGER NOT NULL REFERENCES sequences(id) ON DELETE CASCADE,
    lecture_id  INTEGER NOT NULL REFERENCES lectures(id) ON DELETE CASCADE,
    position    INTEGER NOT NULL,                  -- 1-based order within the sequence
    PRIMARY KEY (sequence_id, lecture_id),
    UNIQUE (sequence_id, position)
);

CREATE INDEX IF NOT EXISTS ix_seqitems_seq ON sequence_items(sequence_id, position);

-- --------------------------------------------------------------------------- cycles

-- Published lecture cycles / compilations, resolved from their own index page on
-- rsarchive (e.g. https://rsarchive.org/Lectures/Easter/). Distinct from `volumes`:
-- a cycle draws its lectures from one or MORE GA volumes, so it is the unit that
-- answers "the Nth of C lectures in <cycle>" for a cross-GA compilation.
--
-- Keyed on `url`, not the title: the title differs in caps/spacing between the GA
-- index cell ("The Festivals and Their Meaning II:  Easter") and the compilation
-- page's own heading ("The Festivals and their Meaning II:Easter").
CREATE TABLE IF NOT EXISTS cycles (
    id            INTEGER PRIMARY KEY,
    url           TEXT NOT NULL UNIQUE,            -- compilation index URL = merge key
    title         TEXT NOT NULL DEFAULT '',
    kind          TEXT NOT NULL DEFAULT 'compilation'
                  CHECK (kind IN ('ga_volume', 'compilation')),
    lecture_count INTEGER,                         -- members found on the index page
    ga_numbers    TEXT NOT NULL DEFAULT '',        -- bare tokens, ascending, comma-separated
    year_range    TEXT NOT NULL DEFAULT '',        -- e.g. "1908-1922"
    created_at    TEXT NOT NULL DEFAULT (datetime('now')),
    updated_at    TEXT NOT NULL DEFAULT (datetime('now')),
    -- v3: 1 = compilation in scope (member bodies ingested via ingest.ingest_index).
    curated       INTEGER NOT NULL DEFAULT 0
);

-- One row per lecture in a cycle, in the cycle's own printed order. `lecture_id` is
-- nullable: a member may not (yet) exist in `lectures`, and we still need its
-- position/ga/date to render the subtitle.
CREATE TABLE IF NOT EXISTS cycle_members (
    cycle_id   INTEGER NOT NULL REFERENCES cycles(id) ON DELETE CASCADE,
    lecture_id INTEGER REFERENCES lectures(id) ON DELETE SET NULL,
    position   INTEGER NOT NULL,                   -- 1-based, from the Roman numeral
    member_url TEXT NOT NULL,
    title      TEXT NOT NULL DEFAULT '',
    date_iso   TEXT NOT NULL DEFAULT '',
    ga         TEXT NOT NULL DEFAULT '',           -- bare token, resolved best-effort
    city       TEXT NOT NULL DEFAULT '',           -- index pages omit it; from `lectures`
    PRIMARY KEY (cycle_id, position)
);

CREATE INDEX IF NOT EXISTS ix_cycle_members_lecture ON cycle_members(lecture_id);
CREATE INDEX IF NOT EXISTS ix_cycle_members_date    ON cycle_members(date_iso);

-- ------------------------------------------------------------------- work_aliases

-- v3: names by which Steiner (or an editor) cites a book or cycle — "Occult Science",
-- "Knowledge of the Higher Worlds", a compilation's title — mapped to exactly one
-- target: a GA volume (ga) XOR a published cycle (cycle_id). Keyed on the normalised
-- form (aliases.normalize_alias) so lookups ignore case, articles and punctuation.
-- source: 'seed' = subjects_seed.WORK_ALIASES; 'volume' / 'cycle' = derived from
-- volumes.title_en / titles_in_volume and cycles.title by aliases.seed_work_aliases
-- (rebuilt on every reseed); 'manual' = user-added, never overwritten by a reseed.
CREATE TABLE IF NOT EXISTS work_aliases (
    alias_norm TEXT PRIMARY KEY,                   -- aliases.normalize_alias(alias)
    alias      TEXT NOT NULL,                      -- display form as first seen
    ga         TEXT REFERENCES volumes(ga) ON UPDATE CASCADE,
    cycle_id   INTEGER REFERENCES cycles(id) ON DELETE CASCADE,
    source     TEXT NOT NULL DEFAULT 'seed'
                 CHECK (source IN ('seed','volume','cycle','manual')),
    CHECK ((ga IS NULL) <> (cycle_id IS NULL))
);

CREATE INDEX IF NOT EXISTS ix_work_aliases_ga    ON work_aliases(ga);
CREATE INDEX IF NOT EXISTS ix_work_aliases_cycle ON work_aliases(cycle_id);

-- ------------------------------------------------------------------------- tafeln

-- Blackboard drawings (Tafeln). May belong to a lecture (lecture_id) and always to a GA.
CREATE TABLE IF NOT EXISTS tafeln (
    id          INTEGER PRIMARY KEY,
    lecture_id  INTEGER REFERENCES lectures(id) ON DELETE SET NULL,
    ga          TEXT NOT NULL,                     -- volume the tafel belongs to
    tafel_num   INTEGER,                           -- NN in {ga}-T{NN}.webp
    image_path  TEXT NOT NULL DEFAULT '',          -- local file path once downloaded
    url         TEXT NOT NULL DEFAULT '',          -- source image url
    caption     TEXT NOT NULL DEFAULT '',
    description TEXT NOT NULL DEFAULT '',           -- LLM/manual visual description (later)
    colors      TEXT NOT NULL DEFAULT '[]',         -- JSON array of colour names/hex
    keywords    TEXT NOT NULL DEFAULT '[]',         -- JSON array of tag keywords
    UNIQUE (ga, tafel_num)
);

CREATE INDEX IF NOT EXISTS ix_tafeln_lecture ON tafeln(lecture_id);
CREATE INDEX IF NOT EXISTS ix_tafeln_ga      ON tafeln(ga);

-- ---------------------------------------------------------------------------- FTS5

-- Optional full-text search over lecture title/summary. The importer wraps the
-- CREATE VIRTUAL TABLE in a try/except (some Python builds lack FTS5); the triggers
-- below keep it in sync with `lectures`. Content is external (content='lectures').
CREATE VIRTUAL TABLE IF NOT EXISTS lectures_fts USING fts5(
    title_en,
    title_de,
    summary,
    cycle_title,
    content='lectures',
    content_rowid='id'
);

CREATE TRIGGER IF NOT EXISTS lectures_ai AFTER INSERT ON lectures BEGIN
    INSERT INTO lectures_fts(rowid, title_en, title_de, summary, cycle_title)
    VALUES (new.id, new.title_en, new.title_de, new.summary, new.cycle_title);
END;

CREATE TRIGGER IF NOT EXISTS lectures_ad AFTER DELETE ON lectures BEGIN
    INSERT INTO lectures_fts(lectures_fts, rowid, title_en, title_de, summary, cycle_title)
    VALUES ('delete', old.id, old.title_en, old.title_de, old.summary, old.cycle_title);
END;

CREATE TRIGGER IF NOT EXISTS lectures_au AFTER UPDATE ON lectures BEGIN
    INSERT INTO lectures_fts(lectures_fts, rowid, title_en, title_de, summary, cycle_title)
    VALUES ('delete', old.id, old.title_en, old.title_de, old.summary, old.cycle_title);
    INSERT INTO lectures_fts(rowid, title_en, title_de, summary, cycle_title)
    VALUES (new.id, new.title_en, new.title_de, new.summary, new.cycle_title);
END;

-- ---------------------------------------------------------------------------- views

-- Chronological lecture read (earliest first; unknown dates last), the canonical
-- ordering used by exports. Mirrors models.Lecture.sort_key().
CREATE VIEW IF NOT EXISTS lectures_chrono AS
    SELECT *
    FROM lectures
    ORDER BY CASE WHEN date_iso = '' THEN '9999-99-99' ELSE date_iso END, url;

-- ------------------------------------------------------------------------- notes
-- Kindle "My Clippings" imports (see catalog/clippings.py). Book-level notes,
-- linked to a volume by GA when resolvable. DDL mirrored in clippings.NOTES_DDL
-- so an already-built catalog.db can migrate additively.
CREATE TABLE IF NOT EXISTS notes (
    id          INTEGER PRIMARY KEY,
    source      TEXT NOT NULL DEFAULT 'kindle',
    book_title  TEXT NOT NULL DEFAULT '',
    book_raw    TEXT NOT NULL DEFAULT '',
    ga          TEXT,
    volume_ga   TEXT REFERENCES volumes(ga),
    note_type   TEXT,
    page        TEXT,
    loc_start   INTEGER,
    loc_end     INTEGER,
    added_iso   TEXT,
    added_raw   TEXT,
    text        TEXT NOT NULL DEFAULT '',
    tags        TEXT NOT NULL DEFAULT '',
    created_at  TEXT NOT NULL DEFAULT (datetime('now'))
);
CREATE INDEX IF NOT EXISTS ix_notes_ga ON notes(ga);
CREATE INDEX IF NOT EXISTS ix_notes_volume ON notes(volume_ga);
CREATE UNIQUE INDEX IF NOT EXISTS ux_notes_dedupe
    ON notes(book_title, IFNULL(loc_start,-1), IFNULL(loc_end,-1), text);
