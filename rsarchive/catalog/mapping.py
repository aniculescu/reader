#!/usr/bin/env python3
"""
rsarchive.catalog.mapping — ``lectures`` row ⇄ :class:`rsarchive.models.Lecture`.

The single owner of the conversion between a ``lectures`` table row and the shared
:class:`~rsarchive.models.Lecture` model (see ``catalog/DESIGN.md`` → ``mapping.py``).
Scalar bibliographic fields map to their own columns; the four rich nested structures
that have no flat representation (``positions`` / ``body`` / ``footnotes`` / ``images``)
are stored as JSON text columns and round-trip losslessly through the ``models.*``
``to_json`` / ``from_json`` constructors.

Round-trip invariant (a test): ``row_to_lecture(conn, <row from upsert_lecture(L)>)``
reproduces ``L.to_json()`` for every field the table stores (``cross_refs`` are NOT
stored — they are regenerated by :mod:`rsarchive.metadata` on export).

stdlib only (``json``, ``sqlite3``); ``from __future__ import annotations`` so it
imports under 3.9.
"""

from __future__ import annotations

import json
import sqlite3
from typing import Any, Dict, Optional

from rsarchive.models import (
    Block,
    Footnote,
    IMAGE_TAFEL,
    Images,
    Lecture,
    Positions,
)

__all__ = ["lecture_to_row", "upsert_lecture", "row_to_lecture"]


# --------------------------------------------------------------------------- helpers

def _field(row: Any, name: str, default: Any = "") -> Any:
    """Read a column from a sqlite3.Row / dict / object with a safe default."""
    if row is None:
        return default
    try:
        val = row[name]
    except (KeyError, IndexError, TypeError):
        val = getattr(row, name, default)
    return default if val is None else val


# ------------------------------------------------------------------- Lecture -> row

def lecture_to_row(lec: Lecture, *, seq_in_volume: Optional[int] = None) -> Dict[str, Any]:
    """Flatten a :class:`Lecture` into a dict of ``lectures`` columns.

    JSON-encodes the four rich structures (``positions`` / ``body`` / ``footnotes`` /
    ``images``). ``title_de`` and ``summary`` are catalog-only enrichments with no
    ``Lecture`` field, so they default to ``""`` here (callers/importers override them).
    Does not touch the DB.
    """
    return {
        "ga": lec.ga,
        "url": lec.url,
        "seq_in_volume": seq_in_volume,
        "title_en": lec.title,
        "title_de": "",
        "date_iso": lec.date_iso,
        "date_display": lec.date_display,
        "city": lec.city,
        "edition_path": lec.edition_path,
        "translator": lec.translator,
        "cycle_title": lec.cycle_title,
        "cycle_url": lec.cycle_url,
        "book_title": lec.book_title,
        "summary": "",
        "positions_json": json.dumps(lec.positions.to_json(), ensure_ascii=False),
        "body_json": json.dumps([b.to_json() for b in lec.body], ensure_ascii=False),
        "footnotes_json": json.dumps(
            [f.to_json() for f in lec.footnotes], ensure_ascii=False
        ),
        "images_json": json.dumps(lec.images.to_json(), ensure_ascii=False),
    }


# ------------------------------------------------------------------- upsert

# Columns updated on an ON CONFLICT(url) collision. seq_in_volume/title_de/summary get
# preserve-when-blank semantics below; the scalars are refreshed from the incoming row.
_REFRESH_COLS = (
    "ga", "title_en", "date_iso", "date_display", "city", "edition_path",
    "translator", "cycle_title", "cycle_url", "book_title",
)


def _rich_refresh_cols(lec: Lecture) -> tuple:
    """The rich JSON columns an upsert of ``lec`` may overwrite on conflict.

    A Lecture built from metadata only (the CSV pass) carries an empty body / empty
    positions / no images; refreshing from it would wipe bodies written by
    :mod:`rsarchive.catalog.ingest`, so an empty structure preserves the stored one.
    ``body_json`` and ``footnotes_json`` travel as a pair (they are parsed together).
    """
    cols = []
    pos = lec.positions
    if pos.primary is not None or pos.subcycle is not None or pos.source_ga or pos.clauses:
        cols.append("positions_json")
    if lec.body:
        cols.extend(("body_json", "footnotes_json"))
    if lec.images.sketches or lec.images.tafeln:
        cols.append("images_json")
    return tuple(cols)

_INSERT_COLS = (
    "ga", "url", "seq_in_volume", "title_en", "title_de", "date_iso",
    "date_display", "city", "edition_path", "translator", "cycle_title",
    "cycle_url", "book_title", "summary", "positions_json", "body_json",
    "footnotes_json", "images_json",
)


def upsert_lecture(
    conn: sqlite3.Connection,
    lec: Lecture,
    *,
    seq_in_volume: Optional[int] = None,
    title_de: str = "",
    summary: str = "",
) -> int:
    """INSERT-or-UPDATE a lecture by its ``url`` (the merge key); return ``lectures.id``.

    Refreshes the mapped scalar/JSON columns from ``lec``, and mirrors any
    ``lec.images.tafeln`` into the ``tafeln`` table (upsert by ``(ga, tafel_num)``).
    Preserve-when-blank fields: ``title_de`` / ``summary`` override an existing value
    only when the incoming argument is non-empty, ``seq_in_volume`` preserves an
    existing value when ``None`` is passed, and an empty ``body`` / ``positions`` /
    ``images`` keeps the stored JSON — so a re-import (or the CSV pass, which has no
    German title / no position / no body) never wipes enrichment written by another
    importer or by body ingestion.
    """
    row = lecture_to_row(lec, seq_in_volume=seq_in_volume)
    if title_de:
        row["title_de"] = title_de
    if summary:
        row["summary"] = summary

    placeholders = ", ".join("?" for _ in _INSERT_COLS)
    columns = ", ".join(_INSERT_COLS)

    set_clauses = [
        f"{c} = excluded.{c}" for c in _REFRESH_COLS + _rich_refresh_cols(lec)
    ]
    # Preserve-when-blank / preserve-when-null semantics on conflict.
    set_clauses.append(
        "title_de = CASE WHEN excluded.title_de != '' "
        "THEN excluded.title_de ELSE lectures.title_de END"
    )
    set_clauses.append(
        "summary = CASE WHEN excluded.summary != '' "
        "THEN excluded.summary ELSE lectures.summary END"
    )
    set_clauses.append(
        "seq_in_volume = COALESCE(excluded.seq_in_volume, lectures.seq_in_volume)"
    )
    set_clauses.append("updated_at = datetime('now')")

    conn.execute(
        "INSERT INTO lectures (" + columns + ") VALUES (" + placeholders + ") "
        "ON CONFLICT(url) DO UPDATE SET " + ", ".join(set_clauses),
        tuple(row[c] for c in _INSERT_COLS),
    )

    lecture_id = int(
        conn.execute("SELECT id FROM lectures WHERE url = ?", (lec.url,)).fetchone()[0]
    )

    # Mirror tafeln (blackboard drawings) into their own table, keyed by (ga, tafel_num).
    for taf in lec.images.tafeln:
        if taf.kind != IMAGE_TAFEL:
            continue
        conn.execute(
            "INSERT INTO tafeln (lecture_id, ga, tafel_num, image_path, url) "
            "VALUES (?, ?, ?, ?, ?) "
            "ON CONFLICT(ga, tafel_num) DO UPDATE SET "
            "lecture_id = excluded.lecture_id, "
            "image_path = CASE WHEN excluded.image_path != '' "
            "THEN excluded.image_path ELSE tafeln.image_path END, "
            "url = CASE WHEN excluded.url != '' THEN excluded.url ELSE tafeln.url END",
            (lecture_id, lec.ga, taf.num, taf.local_path or "", taf.url or ""),
        )

    conn.commit()
    return lecture_id


# ------------------------------------------------------------------- row -> Lecture

def _loads(value: Any, fallback: Any) -> Any:
    """json.loads a text column, tolerating NULL/empty (returns ``fallback``)."""
    if not value:
        return fallback
    try:
        return json.loads(value)
    except (TypeError, ValueError):
        return fallback


def row_to_lecture(conn: sqlite3.Connection, row: Any) -> Lecture:
    """Rebuild a :class:`Lecture` from a ``lectures`` row.

    ``json.loads`` the four ``*_json`` columns and hands them to the ``models.*``
    ``from_json`` constructors. ``cross_refs`` are left empty (they are recomputed by
    :mod:`rsarchive.metadata` on export). The ``conn`` argument is accepted for API
    symmetry / future joins but is not required to rebuild the model.
    """
    positions = Positions.from_json(_loads(_field(row, "positions_json", ""), {}))
    body = [Block.from_json(b) for b in _loads(_field(row, "body_json", ""), [])]
    footnotes = [
        Footnote.from_json(f) for f in _loads(_field(row, "footnotes_json", ""), [])
    ]
    images = Images.from_json(_loads(_field(row, "images_json", ""), {}))

    return Lecture(
        ga=_field(row, "ga", ""),
        url=_field(row, "url", ""),
        edition_path=_field(row, "edition_path", ""),
        title=_field(row, "title_en", ""),
        cycle_title=_field(row, "cycle_title", ""),
        cycle_url=_field(row, "cycle_url", ""),
        book_title=_field(row, "book_title", ""),
        date_iso=_field(row, "date_iso", ""),
        date_display=_field(row, "date_display", ""),
        city=_field(row, "city", ""),
        translator=_field(row, "translator", ""),
        positions=positions,
        body=body,
        footnotes=footnotes,
        images=images,
    )
